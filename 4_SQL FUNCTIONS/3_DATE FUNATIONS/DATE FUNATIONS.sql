CREATE TABLE STUDENT
	(ID INT PRIMARY KEY AUTO_INCREMENT,
	NAME VARCHAR(100) NOT NULL,
	AGE INT CHECK(AGE>=10),
	CITY VARCHAR(100) NOT NULL,
	MARKS INT NOT NULL,
	EMAIL VARCHAR(100) NOT NULL,
    JOINING_DATE VARCHAR(100) NOT NULL);

-- Special Operators

	

-- IN
-- Checks whether a value matches any value in a list.
SELECT *
FROM EMPLOYEES
WHERE CITY IN('HYD','KHMM','SPL');

SELECT *
FROM EMPLOYEES
WHERE CITY IN('HYD','KHMM');

-- BETWEEN
-- Checks whether a value is within a range.

SELECT *
FROM EMPLOYEES
WHERE SALARY BETWEEN 50000 AND 100000;

-- LIKE
-- Used for pattern matching.
SELECT  *
FROM EMPLOYEES
WHERE NAME LIKE 'S%';

SELECT  *
FROM EMPLOYEES
WHERE NAME LIKE '%I';

SELECT *
FROM EMPLOYEES
WHERE NAME LIKE '%A%';

SELECT  *
FROM EMPLOYEES
WHERE NAME LIKE '____';

-- IS NULL
-- Checks for missing (NULL) values.
SELECT *
FROM EMPLOYEES
WHERE EMAIL IS NULL;

SELECT *
FROM EMPLOYEES
WHERE EMAIL IS NOT NULL;


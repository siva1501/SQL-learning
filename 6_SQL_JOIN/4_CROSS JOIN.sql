-- CROSS JOIN
-- CROSS JOIN returns every possible combination of rows from both tables.

CREATE DATABASE COLLEGE;
USE COLLEGE;
CREATE TABLE STUDENT(ID INT PRIMARY KEY,NAME VARCHAR(100),AGE INT,PNO VARCHAR(15),DEPARTMENT_ID INT UNIQUE);
INSERT INTO STUDENT

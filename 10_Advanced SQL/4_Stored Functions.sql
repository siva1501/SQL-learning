DELIMITER //

CREATE FUNCTION TOTAL_MARKS(MONTHLY_MARKS INT)
RETURNS INT
DETERMINISTIC
BEGIN
    RETURN MONTHLY_MARKS* 12;
END //

DELIMITER ;

SELECT NAME, MARKS, TOTAL_MARKS(MARKS) AS YEARLY_MARKS
FROM STUDENT;